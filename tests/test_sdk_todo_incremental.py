# -*- coding: utf-8 -*-
from src.core.pipeline.extraction import add_sdk_todo_to_new_content, merge_tl_content


def test_new_file_gets_sdk_todo_marker():
    content = 'translate spanish start_12345678:\n\n    # e "Hello"\n    e "Hola"\n'
    result = add_sdk_todo_to_new_content(content, timestamp="2026-10-16 09:42")
    assert result.startswith("# TODO: Translation updated at 2026-10-16 09:42\n\n")
    assert content in result


def test_incremental_update_appends_todo_at_end_and_preserves_manual_edit():
    existing = '''# TODO: Translation updated at 2026-10-01 10:00

# game/script.rpy:10
translate spanish start_11111111:

    # e "I love this place."
    e "Este lugar me encanta."
'''
    generated = '''# Translation strings file
# Auto-generated by LinguaNova

# game/script.rpy:99
translate spanish start_22222222:

    # e "We should come back tomorrow."
    e "Deberíamos volver mañana."
'''
    merged = merge_tl_content(existing, generated, "spanish", timestamp="2026-10-16 09:42")
    assert 'e "Este lugar me encanta."' in merged
    assert merged.startswith(existing)
    pos_todo = merged.rfind("# TODO: Translation updated at 2026-10-16 09:42")
    pos_new = merged.rfind("translate spanish start_22222222:")
    assert pos_todo > len(existing) - 5
    assert pos_new > pos_todo


def test_no_new_entries_means_no_new_todo_and_no_rewrite():
    existing = '''translate spanish strings:
    old "Save"
    new "Guardar"
'''
    generated = '''translate spanish strings:
    old "Save"
    new "Guardar"
'''
    assert merge_tl_content(existing, generated, "spanish", timestamp="2026-10-16 09:42") == existing
